#!/usr/bin/env python3
"""Generate DIMACS 9th-challenge query files (.p2p / .ss) for a USA road graph.

WHY THIS EXISTS
---------------
The 9th DIMACS Implementation Challenge never published ready-made query files
for the USA road networks.  Participants were expected to *generate* them locally
with the official benchmark package (ch9-1.1):

  * random point-to-point:  scripts/genUSA-road-d.rnd.p2p.pl
        -> NUMQUERY = 1000 random (source, target) pairs, SEED = 971,
           output: inputs/USA-road-d/USA-road-d.<GRAPH>.p2p
  * local point-to-point:   scripts/genUSA-road-d.loc.p2p.pl
        -> 100 local query sources per Dijkstra-rank class (gens/local_q/)
  * single-source:          scripts/genUSA-road-d.ss.pl
        -> gens/utils/genSources.pl, nsrc = int(10 * n_CTR / n_graph) sources
           (n_CTR = 14081816), output: USA-road-d.<GRAPH>.ss

(The official generator source is preserved under
 data/dimacs/reference/ch9-1.1/scripts/.)

The official genUSA-road-d.rnd.p2p.pl prints "seed 971" but never calls
srand(), so every run produces a different pair set (Perl auto-seeds).  For
reproducible benchmarks this tool generates the same *file format* and
*parameters* with Python's deterministic Mersenne-Twister RNG instead: the same
graph + --seed + --count always gives byte-identical output.

FORMATS (see data/dimacs/reference/ch9-1.1/docs/format/format.html)
------------------------------------------------------------------
.p2p (point-to-point, what Project 2's "1000 source-target pairs" means):
    c ...comments...
    p aux sp p2p <count>
    q <source> <target>
.ss (single-source):
    c ...comments...
    p aux sp ss <count>
    s <source>

These files are GENERATED, not official downloads; do not describe them as
official DIMACS data.  The graphs they refer to are the official DIMACS graphs.

Usage
-----
    python gen-p2p-queries.py data/dimacs/USA-road-d.NY.gr
        -> data/dimacs/queries/USA-road-d.NY.p2p (1000 pairs, seed 971)

    python gen-p2p-queries.py data/dimacs/USA-road-d.NY.gr --ss
    python gen-p2p-queries.py graph.gr -o out.p2p --count 500 --seed 7
    python gen-p2p-queries.py graph.gr --quiet   # only print output path
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

N_CTR = 14_081_816  # node count of the largest DIMACS d-graph (USA-road-d.CTR),
# used by the official genUSA-road-d.ss.pl to scale the number of sources.
SS_MAX_SOURCES = 10  # sources for the largest graph, per official script


def read_header(graph: Path) -> tuple[int, int]:
    """Return (n, m) from the DIMACS 'p sp n m' problem line."""
    try:
        with graph.open("r", encoding="ascii", errors="replace") as f:
            for line in f:
                if line.startswith("p "):
                    tok = line.split()
                    if len(tok) != 4 or tok[1] != "sp":
                        raise ValueError(f"{graph}: unexpected problem line: {line.rstrip()!r}")
                    return int(tok[2]), int(tok[3])
    except OSError as exc:
        raise SystemExit(f"error: cannot read {graph}: {exc}") from exc
    raise ValueError(f"{graph}: no 'p sp n m' problem line found")


def gen_p2p(graph: Path, out: Path, count: int, seed: int) -> None:
    n, _m = read_header(graph)
    rng = random.Random(seed)
    with out.open("w", encoding="ascii", newline="\n") as f:
        f.write("c 9th DIMACS Implementation Challenge: Shortest Paths\n")
        f.write("c http://www.dis.uniroma1.it/~challenge9\n")
        f.write("c USA-road-d family p2p problem aux file\n")
        f.write("c GENERATED by pq-test/tools/gen-p2p-queries.py "
                f"(count={count} seed={seed}); NOT an official download\n")
        f.write("c\n")
        f.write(f"p aux sp p2p {count}\n")
        f.write(f"c graph contains {n} nodes\n")
        f.write(f"c file contains {count} query pairs\n")
        f.write("c\n")
        for _ in range(count):
            src = rng.randrange(1, n + 1)  # official: 1 + int(rand(n))
            dst = rng.randrange(1, n + 1)
            f.write(f"q {src} {dst}\n")
    print(f"wrote {out}  ({count} query pairs, graph n={n}, seed={seed})")


def gen_ss(graph: Path, out: Path, seed: int) -> None:
    n, _m = read_header(graph)
    # official genUSA-road-d.ss.pl: nsrc = int(MINNSRC * n_CTR / n)
    nsrc = max(1, int(SS_MAX_SOURCES * N_CTR / n))
    nsrc = min(nsrc, n)
    rng = random.Random(seed)
    sources = sorted(rng.sample(range(1, n + 1), nsrc))
    with out.open("w", encoding="ascii", newline="\n") as f:
        f.write("c 9th DIMACS Implementation Challenge: Shortest Paths\n")
        f.write("c http://www.dis.uniroma1.it/~challenge9\n")
        f.write("c USA-road-d family single-source problem aux file\n")
        f.write("c GENERATED by pq-test/tools/gen-p2p-queries.py (seed=%d); "
                "NOT an official download\n" % seed)
        f.write("c\n")
        f.write(f"p aux sp ss {nsrc}\n")
        f.write(f"c graph contains {n} nodes\n")
        f.write(f"c file contains {nsrc} source lines\n")
        f.write("c\n")
        for s in sources:
            f.write(f"s {s}\n")
    print(f"wrote {out}  ({nsrc} sources, graph n={n}, seed={seed})")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate DIMACS-style .p2p/.ss query files for a USA road graph.")
    ap.add_argument("graph", type=Path, help="DIMACS .gr graph file")
    ap.add_argument("-o", "--out", type=Path, default=None, help="output query file")
    ap.add_argument("--count", type=int, default=1000, help="number of query pairs (.p2p), default 1000")
    ap.add_argument("--seed", type=int, default=971, help="RNG seed, default 971 (official intent)")
    ap.add_argument("--ss", action="store_true", help="generate a single-source .ss file instead of .p2p")
    ap.add_argument("--quiet", action="store_true", help="only print the output path")
    args = ap.parse_args(argv)

    if args.count <= 0:
        raise SystemExit("error: --count must be positive")

    graph = args.graph
    if args.out is None:
        out_dir = Path("data/dimacs/queries")
        out_dir.mkdir(parents=True, exist_ok=True)
        suffix = ".ss" if args.ss else ".p2p"
        stem = graph.name
        for ext in (".gr.gz", ".gr", ".gz"):
            if stem.endswith(ext):
                stem = stem[: -len(ext)]
                break
        args.out = out_dir / (stem + suffix)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)

    try:
        if args.ss:
            gen_ss(graph, args.out, args.seed)
        else:
            gen_p2p(graph, args.out, args.count, args.seed)
    except ValueError as exc:
        raise SystemExit(f"error: {exc}") from exc

    if args.quiet:
        print(args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
